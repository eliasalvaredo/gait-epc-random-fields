from epc_gait import (angular_resample, build_random_field, dmepc,  # noqa: E402
                      epc_curve, euler_characteristic, fit_dmepc, polynomize,
                      remove_high_sd_cycles, synthetic_vgrf)


def test_euler_simple_shapes():
    empty = np.zeros((5, 5))
    blob = np.zeros((7, 7)); blob[2:5, 2:5] = 1
    ring = np.ones((5, 5)); ring[2, 2] = 0
    two_blobs = np.zeros((5, 9)); two_blobs[1:3, 1:3] = 1; two_blobs[1:3, 5:8] = 1
    diagonal = np.array([[1, 0], [0, 1]])  # one component with 8-connectivity
    assert euler_characteristic(empty) == 0
    assert euler_characteristic(blob) == 1
    assert euler_characteristic(ring) == 0          # 1 component - 1 hole
    assert euler_characteristic(two_blobs) == 2
    assert euler_characteristic(diagonal) == 1


def test_euler_matches_connected_components():
    from scipy import ndimage
    rng = np.random.default_rng(0)
    for _ in range(50):
        img = rng.random((30, 40)) < 0.3
        _, n_components = ndimage.label(img, structure=np.ones((3, 3)))
        _, n_bg = ndimage.label(np.pad(~img, 1, constant_values=True))  # 4-connected
        n_holes = n_bg - 1
        assert euler_characteristic(img) == n_components - n_holes


def test_angular_resampling_equalizes_strides():
    x, _ = synthetic_vgrf(n_strides=60, seed=1)
    x_res, stride, info = angular_resample(x, samples_per_stride=200)
    assert abs(len(x_res) / 200 - 60) <= 2
    assert np.allclose(np.diff(stride), 1 / 200)


def test_full_pipeline_and_dmepc():
    x, _ = synthetic_vgrf(seed=2)
    x_res, _, _ = angular_resample(x)
    rf = build_random_field(x_res)
    assert rf.shape[1] == 170 and rf.shape[0] > 30
    rf_clean, removed = remove_high_sd_cycles(rf)
    assert rf_clean.shape[0] == rf.shape[0] - len(removed)
    rf_poly, degree = polynomize(rf_clean)
    u = np.arange(-0.2, 1.8, 0.01)
    epc = epc_curve(rf_poly, u)
    assert epc[0] == 1 and epc[-1] == 0  # one component below the field, empty above

    # The PSO must recover a curve generated by the model itself
    # (a higher inertia weight explores better on this clean, well-posed target)
    true = np.array([5, 20, -3, 8, 0.05, 0.1, 0.2, 0.6])
    target = dmepc(u, true, 2)
    params, cost = fit_dmepc(u, target, sm=2, w=0.5, seed=0)
    assert cost < 0.01


